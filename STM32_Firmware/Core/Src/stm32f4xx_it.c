void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size)
{
    // --- 判断是哪个串口接收到了数据 ---

    if (huart->Instance == USART1) // 如果是来自 FPGA (UART1) 的数据
    {
        // 1. 调用FPGA数据处理函数
        App_FPGA_Data_RxCallback(g_fpga_rx_buffer, Size);

        // 2. 重新启动对FPGA串口的接收 (至关重要!)
        HAL_UARTEx_ReceiveToIdle_DMA(&huart1, g_fpga_rx_buffer, FPGA_RX_BUFFER_SIZE);
        __HAL_DMA_DISABLE_IT(huart1.hdmarx, DMA_IT_HT);
    }
    else if (huart->Instance == USART2) // 如果是来自 HMI (UART2) 的数据
    {
        // 1. 调用HMI指令处理函数
        App_HMI_RxCallback(g_hmi_rx_buffer, Size);

        // 2. 重新启动对HMI串口的接收 (至关重要!)
        HAL_UARTEx_ReceiveToIdle_DMA(&huart2, g_hmi_rx_buffer, HMI_RX_BUFFER_SIZE);
        __HAL_DMA_DISABLE_IT(huart2.hdmarx, DMA_IT_HT);
    }
}
